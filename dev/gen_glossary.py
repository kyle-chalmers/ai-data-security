#!/usr/bin/env python3
"""Regenerate the check-ID table in docs/glossary.md from reference/checks.yml.

The registry is the single source of truth for check titles, so the glossary table is
generated rather than hand-written: a new or renamed check can never leave the glossary
behind. Everything outside the markers is hand-written and left untouched.

    python3 dev/gen_glossary.py          # rewrite the table in place
    python3 dev/gen_glossary.py --check  # exit 1 if the table is stale (used by validate.sh)

Stdlib only.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "reference" / "checks.yml"
GLOSSARY = ROOT / "docs" / "glossary.md"
START = "<!-- checks:start (generated by dev/gen_glossary.py; edit reference/checks.yml instead) -->"
END = "<!-- checks:end -->"


def render(checks: dict) -> str:
    lines = [START, ""]
    current = None
    for check_id, check in checks.items():
        skill = check["skill"]
        if skill != current:
            if current is not None:
                lines.append("")
            lines += [f"**{skill}**", "", "| ID | What it means |", "|---|---|"]
            current = skill
        title = check["title"].replace("|", "\\|")
        lines.append(f"| `{check_id}` | {title} |")
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/glossary.md is stale")
    args = ap.parse_args()

    checks = json.loads(REGISTRY.read_text(encoding="utf-8"))["checks"]
    text = GLOSSARY.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"FAIL: {GLOSSARY.relative_to(ROOT)} is missing the generated-table markers", file=sys.stderr)
        return 1
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    updated = head + render(checks) + tail

    if args.check:
        if updated != text:
            print("FAIL: docs/glossary.md check table is stale; run python3 dev/gen_glossary.py", file=sys.stderr)
            return 1
        print(f"glossary: OK ({len(checks)} checks)")
        return 0
    GLOSSARY.write_text(updated, encoding="utf-8")
    print(f"glossary: wrote {len(checks)} checks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
